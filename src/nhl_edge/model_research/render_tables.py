"""Render RESULTS_TABLES.md from the committed machine-readable results (every number in the narrative reports can be checked here).

    python -m nhl_edge.model_research.render_tables --repo .
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from nhl_edge.model_research import registry

ROOT = "docs/research/nhl-model-improvement"


def f(x: Any, nd: int = 4, pct: bool = False) -> str:
    if x is None:
        return ""
    if isinstance(x, str):
        return x
    return f"{x * 100:.1f}%" if pct else f"{x:.{nd}f}"


def ci(d: dict[str, Any], nd: int = 4) -> str:
    return f"{d['delta']:+.{nd}f} [{d['lo95']:+.{nd}f}, {d['hi95']:+.{nd}f}]"


def table(head: list[str], rows: list[list[str]]) -> str:
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|", *("| " + " | ".join(r) + " |" for r in rows)]) + "\n"


def render(repo: Path) -> str:
    D = repo / ROOT / "data"
    J = lambda n: json.loads((D / n).read_text())  # noqa: E731
    out = ["# Results tables (generated)\n", "> Generated by `python -m nhl_edge.model_research.render_tables` from `data/*.json` and the experiment registry. RESEARCH_ONLY. Do not edit by hand.\n"]
    ents = registry.read(repo / ROOT / "experiment_registry.jsonl")
    res = [e for e in ents if e["type"] == "RESULT"]
    out.append("## Experiment registry (append-only, hash-chained)\n")
    out.append(table(["seq", "id", "tier", "revision", "decision"], [[str(e["seq"]), e["id"], next((p.get("tier", "") for p in ents if p["type"] == "PREREG" and p["id"] == e["id"]), ""), str(e.get("revision", 1)), e.get("decision", "")] for e in res]))
    c = J("cal_experiments.json")
    t = c["dist_describe_V1_all_2624"]
    out.append("## M-DIST-1: V1 predictive distribution vs 2,624 walk-forward games\n")
    out.append(f"Total-goals standardised squared residual: {t['total_z2']['mean']:.3f} (95% CI {t['total_z2']['lo95']:.3f}-{t['total_z2']['hi95']:.3f}); 1.00 = right width, <1 = predictive distribution too wide. "
               f"Predicted mean total {t['mean_total']['pred']:.3f} vs observed {t['mean_total']['obs']:.3f}; predicted variance {t['var_total']['pred_mean_var']:.3f} vs observed {t['var_total']['obs_var']:.3f}.\n")
    out.append(table(["statistic", "predicted", "observed", "observed 95% CI", "prediction inside CI"],
                     [[k, f(v.get("pred", v.get("pred_indep_approx")), 3, True), f(v["obs"], 3, True), f"{v['obs_lo95'] * 100:.1f}%-{v['obs_hi95'] * 100:.1f}%", str(v.get("obs_in_ci_of_pred", ""))] for k, v in t["tails"].items()]))
    out.append("PIT deciles (uniform = calibrated; chi2 critical 16.9, df 9): " + "; ".join(f"{k}: {t[f'pit_{k}']['deciles']} chi2={t[f'pit_{k}']['chi2_10bin']:.1f}" for k in ("total", "home", "away", "margin")) + "\n")
    out.append("## M-CAL-1/2: rolling-origin challengers (paired game-bootstrap deltas vs V1; negative = challenger better)\n")
    for tier in ("EVAL_A", "EVAL_B"):
        n = c["n_eval_A"] if tier == "EVAL_A" else c["n_eval_B"]
        out.append(f"**{tier} (n={n} games)**\n")
        rows = []
        for m in ("rps_total", "rps_margin", "rps_home", "rps_away", "brier_win", "ll_win", "brier_over5.5", "brier_over6.5", "brier_ot"):
            mm = c["mean_loss"][tier]
            rows.append([m, f(mm["V1"][m]), f(mm["C1"][m]), ci(c["paired_vs_V1"][tier]["C1"][m]), f(mm["LEAGUE_POISSON"][m]), ci(c["paired_vs_V1"][tier]["LEAGUE_POISSON"][m])])
        out.append(table(["metric", "V1", "C1", "C1 - V1 [95% CI]", "league Poisson", "league Poisson - V1 [95% CI]"], rows))
    out.append(f"C2 (strength noise): rolling sigma = 0 on every date; log-score by sigma {c['sigma_scores_all_eval_games']}.\n")
    s = J("wf_scan.json")
    out.append("## M-SCAN-1: systematic-error scan (BH q = 0.10 over 17 tests)\n")
    out.append(table(["test", "coef per SD", "SE", "t", "p", "p (BH)", "significant"], [[r["test"], f(r["coef_per_sd"]), f(r["se"]), f(r["t"], 2), f(r["p"], 4), f(r["p_bh"], 4), str(r["bh_sig_q10"])] for r in s]))
    g = J("goalie_ladder.json")
    out.append("## M-GOALIE-1: starting-goalie status ladder at T-60\n")
    out.append(table(["status", "n", "matched", "rate", "Wilson 95%", "stated", "verdict"], [[k, str(v["n"]), str(v["matched"]), f(v["rate"], 3, True), f"{v['wilson_lo95'] * 100:.1f}-{v['wilson_hi95'] * 100:.1f}%", f(v["stated_confidence"], 3), v["verdict"]] for k, v in g["by_status"].items()]))
    L = J("live_challenger.json")
    out.append("## M-LIVE-1: single look at 151 LIVE games\n")
    out.append(table(["metric", "V1", "C1 (frozen)", "C1 - V1 [95% CI]"], [[m, f(L["mean"]["V1"][m]), f(L["mean"]["C1"][m]), ci(L["paired_C1_minus_V1"][m])] for m in ("rps_total", "rps_margin", "brier_win", "ll_win")]))
    ml = L["moneyline_game_level"]
    out.append(f"Moneyline Brier on {ml['n_with_sportsbook']} games with a sportsbook consensus: sportsbook {ml['brier_sportsbook']:.4f}, V1 {ml['brier_V1_same_games']:.4f}, C1 {ml['brier_C1_same_games']:.4f}, V2 {ml['brier_V2_same_games']:.4f}; V1 - sportsbook {ci(ml['paired_V1_minus_sportsbook'])}.\n")
    rows = [[arm, fam, str(v["n_games"]), f(v["brier_model"]), f(v["brier_mid"]), ci(v["model_minus_mid"])] for arm, fs in L["kalshi_t60_families"].items() for fam, v in fs.items()]
    out.append(table(["model", "family", "games", "Brier model", "Brier Kalshi T-60 mid", "model - mid [95% CI]"], rows))
    M = J("market_incremental.json")
    out.append("## M-MKT-1: incremental information beyond the Kalshi T-60 mid (2025-26 history, rolling-origin from 2025-12-01)\n")
    rows = [[arm, fam, str(v["n_games"]), f(v["brier"]["mid"]), f(v["brier"]["cal"]), f(v["brier"]["inc"]), f(v["brier"]["model"]), ci(v["inc_minus_mid"]), ci(v["model_minus_mid"]), f(v["final_c"], 2)]
            for arm, fs in M["families"].items() for fam, v in fs.items()]
    out.append(table(["model", "family", "games", "mid", "calibrated mid", "mid + c*gap", "model alone", "inc - mid [95% CI]", "model - mid [95% CI]", "final c"], rows))
    sc = J("script_calibration.json")
    out.append("## M-SCRIPT-1: NHL_SCRIPT_V1 calibration (LIVE games with a script forecast and postmortem)\n")
    out.append(f"n={sc['n_games']}; multiclass Brier {sc['brier_model']:.4f} vs base-rate {sc['brier_base_rate']:.4f}; paired delta {ci(sc['paired_brier_model_minus_base'])}; top-script hit {sc['top_script_hit_rate']:.3f}.\n")
    out.append(table(["script", "mean predicted", "observed", "obs 95%", "base rate", "inside CI"], [[k, f(v["mean_predicted"], 3, True), f(v["observed_rate"], 3, True), f"{v['obs_lo95'] * 100:.1f}-{v['obs_hi95'] * 100:.1f}%", f(v["base_rate"], 3, True), str(v["calibration_in_ci"])] for k, v in sc["per_script"].items()]))
    info = J("info_events.json")
    out.append("## M-INFO-1: goalie confirmations with a source timestamp\n")
    cl = info["capture_lag_min"]
    out.append(f"{info['n_confirmation_events_with_source_time']} confirmations carry a source report time; {info['n_change_events']} changed the expected starter. Our capture lag behind the source report: median {cl['median']:.1f} min (p25 {cl['p25']:.1f}, p75 {cl['p75']:.1f}); {cl['share_under_15min']:.0%} captured within 15 minutes.\n")
    rows = [[g_, h, str(v[h]["n"]), f(v[h]["mean_abs_move_pts"], 2), f(v[h]["mean_signed_move_pts"], 2), f(v[h]["mean_abs_move_placebo_pts"], 2)] for g_, v in info["groups"].items() for h in ("h15", "h30", "h60", "h120")]
    out.append(table(["group", "horizon", "n", "mean |move| (cents)", "mean signed move", "placebo |move|"], rows))
    out.append(table(["horizon", "CHANGE - SAME |move| (cents)", "95% CI", "n change", "n same"], [[h, f(v["diff"], 3), f"[{v['lo95']:.3f}, {v['hi95']:.3f}]", str(v["n_change"]), str(v["n_same"])] for h, v in info["change_minus_same_abs_move_pts"].items()]))
    P = J("player_usage.json")
    out.append("## M-PLAYER-1: PLAYER_SIM_V1 usage at T-60 (actual - expected, game-clustered 95% CI)\n")
    out.append(table(["quantity", "mean error", "95% CI"], [[k, f(P[f'bias_{k}']['mean'], 3), f"[{P[f'bias_{k}']['lo95']:.3f}, {P[f'bias_{k}']['hi95']:.3f}]"] for k in ("toi_err", "pp_err", "shots_err", "pts_err", "goals_err", "ast_err")]))
    out.append(f"{P['n_dressed']} dressed priced player-games over 145 games; {P['share_priced_not_dressed']:.1%} of priced players did not dress; TOI p10-p90 coverage {P['toi_p10_p90_coverage']['observed']:.1%} (nominal 80%); "
               f"shots variance/mean {P['shots_dispersion']['obs_var_over_mean_actual']:.2f}; P(1+ point) Brier {P['p_1plus_point']['brier']:.4f} vs league-rate {P['p_1plus_point']['brier_constant_league_rate']:.4f}.\n")
    rr = J("registry_v11_reclassification.json")
    out.append("## Registry v1.0 -> v1.1 (reclassification of the frozen results; v1.0 is untouched)\n")
    out.append(table(["id", "title", "v1.0", "v1.1", "tiers with MDE80 > 10% ROI"], [[k, v["title"], v["class_v10"], v["class_v11"], ", ".join(v["underpowered_tiers"])] for k, v in rr["rows"].items()]))
    o20 = J("oct20_case_model_view.json")
    out.append("## October 20 wagers: model view (explanatory, not a validation sample)\n")
    out.append(table(["game", "contract (side)", "fill vs drop (min)", "price", "V1 p(side)", "V2 p(side)", "Kalshi p(side) at T-60", "V1 EV/contract at fill", "result", "net P/L"],
                     [[o["game"], f"{o['ticker'].split('-')[-1]} {o['side']} (line {o['line']})", f(o["minutes_vs_scheduled_drop"], 1), f(o["price"], 2), f(o["v1_p_side"], 3), f(o["v2_p_side"], 3),
                       f(o["kalshi_p_side_at_cut"], 3), f(o["v1_net_ev_per_contract_at_fill"], 3), f"{o['result']} ({o['score']})", f(o["net_pl"], 2)] for o in o20]))
    sh = J("shadow_summary_fixed_engine.json")
    out.append("## Shadow expression engine replay on 151 LIVE games after the review fixes\n")
    out.append(table(["policy", "bets", "games with a bet", "net ROI", "95% CI", "claimed EV/contract"],
                     [[k, str(sh[k]["n_bets"]), str(sh[k]["games_with_bet"]), f(sh[k].get("roi_net"), 3, True) if sh[k].get("roi_net") is not None else "", (f"[{sh[k]['roi_lo95'] * 100:.1f}%, {sh[k]['roi_hi95'] * 100:.1f}%]" if sh[k].get("roi_lo95") is not None else ""), f(sh[k].get("claimed_ev_per_contract"), 3)] for k in ("strict", "research_unvalidated", "naive_ev")]))
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", type=Path, default=Path("."))
    a = ap.parse_args()
    (a.repo / ROOT / "RESULTS_TABLES.md").write_text(render(a.repo))
    print("ok")
